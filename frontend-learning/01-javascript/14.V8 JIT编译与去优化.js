// ========== 三、OSR（长循环热点的处理） ==========

console.log('\n===== 练习 5：OSR 存在的必要性 =====')
// 一个函数被调用一次，但内部循环 1 亿次：
function onceButHugeLoop() {
  let total = 0
  for (let i = 0; i < 100000000; i++) {
    total += i // 真正的热点在循环体
  }
  return total
}

console.time('OSR 优化的长循环')
const r = onceButHugeLoop()
console.timeEnd('OSR 优化的长循环')
console.log('结果:', r)

